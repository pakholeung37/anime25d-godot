'use strict';
// Generated identifiers only: formulas remain handwritten and are checked against the CPU oracle.
const fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, 'addons/anime25d/Core', name), 'utf8');
const snake = name => name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();
function enumeration(source, name, prefix = '', offset = 0) {
    const body = source.match(new RegExp('(?:public|internal) enum ' + name + '\\s*\\{([^}]+)\\}'))[1];
    return body.split(',').map(value => value.trim()).filter(Boolean)
        .map((value, index) => `const int ${prefix}${snake(value)} = ${index + offset};`).join('\n');
}
const definitions = read('Model/RigDefinition.cs');
const tuning = read('Configuration/DeformationSettings.cs').split('public sealed record DeformationSettings')[1];
const uniforms = [...tuning.matchAll(/public double (\w+)/g)]
    .map(match => `uniform float tuning_${snake(match[1]).toLowerCase()};`).join('\n');
const parameters = enumeration(read('Parameters/Parameters.cs'), 'Parameter');
const channels = fs.readFileSync(path.join(root, 'addons/anime25d/Rendering/PoseChannel.cs'), 'utf8');
const output = '// Generated by tools/shader-bindings.cjs. Do not edit indices by hand.\n'
    + parameters + '\n'
    + ['PartRole', 'PartGroup', 'PartSide', 'FadeMode'].map((type, i) => enumeration(definitions, type, ['ROLE_', 'GROUP_', 'SIDE_', 'FADE_'][i])).join('\n')
    + '\n' + enumeration(channels, 'PoseChannel', '', parameters.split('\n').length) + '\n'
    + uniforms + '\n';
const target = path.join(root, 'addons/anime25d/Shaders/bindings.gdshaderinc');
if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== output) throw Error('Shader binding drift. Run node tools/shader-bindings.cjs --write.');
    console.log('Shader parameter, role, and tuning bindings match C# definitions.');
} else if (process.argv.includes('--write')) fs.writeFileSync(target, output);
else process.stdout.write(output);
